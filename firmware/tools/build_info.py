# Pre-build: write the build timestamp into a header that only ota.cpp includes.
# (A -D flag with the time would change every file's compile command and force a full rebuild.)
import time
Import("env")  # noqa: F821
path = env.subst("$PROJECT_SRC_DIR/build_info.h")  # noqa: F821
with open(path, "w") as f:
    f.write("// Generated by tools/build_info.py\n#pragma once\n#define FW_BUILD_TIME \"%d\"\n" % int(time.time()))
