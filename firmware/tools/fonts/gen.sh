#!/usr/bin/env bash
# Generates LVGL fonts (Latin + Cyrillic + symbols) into src/ui/fonts/.
# Usage: firmware/tools/fonts/gen.sh   (needs network: Google Fonts + npm)
# Add a font: one line in FONTS below. Big clock sizes use DIGITS only to save flash.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
FW="$(cd "$HERE/../.." && pwd)"
TTF="$HERE/ttf"
OUT="$FW/src/ui/fonts"
mkdir -p "$TTF" "$OUT"

TEXT="0x20-0x7E,0xA0-0x17F,0x400-0x45F,0x2010-0x2014,0x2018-0x201E,0x2022,0x2026,0x20AC,0x2116,0x2212"   # + Latin-1/Ext-A (Serbian latin), full Cyrillic (Serbian), quotes: notification text
DIGITS="0x20,0x2B,0x2C,0x2D,0x2E,0x30-0x3A,0xB0,0x2212"
VALUES="0x20,0x25,0x2B,0x2C,0x2D,0x2E,0x2F,0x30-0x3A,0xB0,0x20AC,0x2014,0x2212,0x43A"   # digits, %, €, °, dash, minus, slash, "к"
ASCDIG="0x20,0x2B-0x2E,0x30-0x3A"                                                     # digits without the typographic minus (theme fonts lack U+2212)
ASCVAL="0x20,0x25,0x2B-0x2F,0x30-0x3A,0xB0,0x20AC,0x43A"
CYRUP="0x20,0x401,0x410-0x42F"                                                        # А-Я, Ё (word clock grid)
# single emoji, monochrome (Noto Emoji); keep in sync with emoji() in lib/core/ancs.cpp
EMOJI="0x203C,0x2049,0x2122,0x2139,0x2194-0x21AA,0x231A-0x23FF,0x24C2,0x25AA-0x25FE,0x2600-0x27BF,0x2934,0x2935,0x2B05-0x2B55,0x3030,0x303D,0x3297,0x3299,0x1F004-0x1F0CF,0x1F170-0x1F1E5,0x1F200-0x1F251,0x1F300-0x1F3FA,0x1F400-0x1FAFF"
PIXEL="0x20-0x5F,0x401,0x410-0x42F,0xB0,0x20AC,0x2665"                                # uppercase Latin/Cyrillic, digits, punctuation
# LVGL built-in LV_SYMBOL_* glyphs (battery, charge, wifi, bluetooth, bell, ...), merged into text fonts
SYMBOLS="61441,61448,61451,61452,61453,61457,61459,61461,61465,61468,61473,61478,61479,61480,61502,61507,61512,61515,61516,61517,61521,61522,61523,61524,61543,61544,61550,61552,61553,61556,61559,61560,61561,61563,61587,61589,61636,61637,61639,61641,61664,61671,61674,61683,61724,61732,61787,61931,62016,62017,62018,62019,62020,62087,62099,62212,62189,62810,63426,63650"
FA_WOFF="$TTF/FontAwesome5-Solid+Brands-Regular.woff"
[[ -s "$FA_WOFF" ]] || curl -fsSL "https://github.com/lvgl/lvgl/raw/v9.6.0/scripts/generators/built_in_font/FontAwesome5-Solid%2BBrands%2BRegular.woff" -o "$FA_WOFF"

# name            family           weight size range   symbols [fallback font]
FONTS=(
  "f_emoji_12      Noto_Emoji       500    12   EMOJI   no"
  "f_emoji_14      Noto_Emoji       500    14   EMOJI   no"
  "f_emoji_20      Noto_Emoji       500    20   EMOJI   no"
  "f_text_12       Inter            600    12   TEXT    no      f_emoji_12"
  "f_text_14       Inter            600    14   TEXT    yes     f_emoji_14"
  "f_text_20       Inter            800    20   TEXT    no      f_emoji_20"
  "f_digits_24     Inter            800    24   VALUES  no"
  "f_digits_40     Inter            800    40   DIGITS  no"
  "f_digits_48     Inter            800    48   DIGITS  no"
  "f_oswald_104    Oswald           600    104  DIGITS  no"
  "f_mono_14       JetBrains_Mono   400    14   TEXT    no"
  "f_mono_19       JetBrains_Mono   700    19   CYRUP   no"
  "f_mono_54       JetBrains_Mono   700    54   ASCDIG  no"
  "f_pixel_16      Press_Start_2P   400    16   PIXEL   no"
  "f_pixel_40      Press_Start_2P   400    40   ASCDIG  no"
  "f_unb_22        Unbounded        800    22   ASCVAL  no"
  "f_unb_52        Unbounded        800    52   ASCDIG  no"
)

fetch() { # family weight -> path
  local family="$1" weight="$2" file="$TTF/${1// /_}-$2.ttf"
  if [[ ! -s "$file" ]]; then
    local url
    url="$(curl -fsS -A 'Mozilla/4.0' "https://fonts.googleapis.com/css2?family=${family// /+}:wght@${weight}" | grep -oE 'https://[^)]+\.ttf' | head -n1)"
    curl -fsSL "$url" -o "$file"
  fi
  echo "$file"
}

for spec in "${FONTS[@]}"; do
  read -r name family weight size range symbols fallback <<<"$spec"; family="${family//_/ }"
  [[ -n "${ONLY:-}" && " $ONLY " != *" $name "* ]] && continue # ONLY="f_a f_b" regenerates just those
  ttf="$(fetch "$family" "$weight")"
  r="${!range}"
  bpp=4; [[ "$family" == "Press Start 2P" ]] && bpp=1 # pixel font: crisp, 1 bit
  args=(--bpp "$bpp" --size "$size" --format lvgl --no-compress --lv-include lvgl.h -o "$OUT/$name.c" --font "$ttf" -r "$r")
  [[ "$symbols" == yes ]] && args+=(--font "$FA_WOFF" -r "$SYMBOLS")
  npx --yes --registry=https://registry.npmjs.org/ lv_font_conv@1.5.2 "${args[@]}"
  if [[ -n "${fallback:-}" ]]; then # lv_font_conv 1.5.2 has no --lv-fallback: patch the descriptor
    perl -0pi -e "s|(/\\*Initialize a public general font descriptor\\*/)|extern const lv_font_t $fallback;\\n\\1|; s|(\\.dsc = &font_dsc)|.fallback = &$fallback,\\n    \\1|" "$OUT/$name.c"
  fi
  echo "$name: $(wc -c <"$OUT/$name.c") bytes of C"
done

# header with declarations
{
  echo "// Generated by tools/fonts/gen.sh"
  echo "#pragma once"
  echo "#include <lvgl.h>"
  for spec in "${FONTS[@]}"; do read -r name _ <<<"$spec"; echo "LV_FONT_DECLARE($name);"; done
} >"$OUT/fonts.h"
