#!/usr/bin/env bash
# First-time configuration: writes firmware/include/secrets.h and firmware/ota_secrets.ini (both gitignored).
# Usage: scripts/setup.sh            (asks interactively; existing files are kept unless you confirm)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SECRETS="$ROOT/firmware/include/secrets.h"
OTA_INI="$ROOT/firmware/ota_secrets.ini"

if [[ -f "$SECRETS" || -f "$OTA_INI" ]]; then
  read -r -p "secrets.h / ota_secrets.ini already exist. Overwrite? [y/N] " ans
  [[ "$ans" == [yY]* ]] || { echo "Kept existing files."; exit 0; }
fi

echo "Wi-Fi is used for NTP time sync and wireless updates while the watch is charging (2.4 GHz only)."
read -r -p "Wi-Fi SSID (empty = no Wi-Fi): " ssid
pass=""
[[ -n "$ssid" ]] && { read -r -s -p "Wi-Fi password: " pass; echo; }
read -r -s -p "OTA password for wireless updates (empty = generate one): " ota; echo
if [[ -z "$ota" ]]; then
  ota="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 20 || true)"
  echo "Generated OTA password (also saved in firmware/ota_secrets.ini): $ota"
fi

esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
cat >"$SECRETS" <<H
// Generated by scripts/setup.sh. Gitignored: never commit.
#pragma once

#define WIFI_SSID    "$(esc "$ssid")"
#define WIFI_PASS    "$(esc "$pass")"

// OTA upload password (must match firmware/ota_secrets.ini)
#define OTA_PASSWORD "$(esc "$ota")"

// Companion server (planned, unused for now)
#define SERVER_URL   ""
#define SERVER_TOKEN ""
H
cat >"$OTA_INI" <<I
; Generated by scripts/setup.sh. Gitignored: never commit.
[ota]
password = $ota
host = twatch.local
I
chmod 600 "$SECRETS" "$OTA_INI"
echo "Wrote firmware/include/secrets.h and firmware/ota_secrets.ini. Next: scripts/flash_usb.sh"
